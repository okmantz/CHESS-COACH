// Regenerates sw.js with the current file list and a content hash (so installed apps update when files change).
// Run:  node scripts/gen-sw.mjs      (the GitHub Pages workflow runs it automatically)
import fs from 'node:fs';
import path from 'node:path';
import crypto from 'node:crypto';

const root = path.resolve(path.dirname(new URL(import.meta.url).pathname), '..');
const skip = new Set(['.git', '.github', 'node_modules', 'scripts', 'tests', 'sw.js']);
const files = [];
(function walk(dir) {
  for (const f of fs.readdirSync(dir)) {
    if (skip.has(f) || f.startsWith('.')) continue;
    const p = path.join(dir, f);
    if (fs.statSync(p).isDirectory()) walk(p); else if (!/\.(md|txt|map)$/i.test(f) || /Copying\.txt$/.test(f)) files.push(path.relative(root, p).split(path.sep).join('/'));
  }
})(root);
files.sort();
const hash = crypto.createHash('sha1');
for (const f of files) { hash.update(f); hash.update(fs.readFileSync(path.join(root, f))); }
const version = hash.digest('hex').slice(0, 10);
const heavy = files.filter((f) => f.endsWith('.wasm'));

const sw = `// AUTO-GENERATED by scripts/gen-sw.mjs — do not edit by hand.
const VERSION = 'chesscoach-${version}';
const ASSETS = ${JSON.stringify(['./', ...files], null, 1)};

self.addEventListener('install', (e) => {
  e.waitUntil(caches.open(VERSION).then((c) => Promise.all(ASSETS.map((a) => c.add(new Request(a, { cache: 'reload' })).catch(() => null)))).then(() => self.skipWaiting()));
});
self.addEventListener('activate', (e) => {
  e.waitUntil(caches.keys().then((keys) => Promise.all(keys.filter((k) => k.startsWith('chesscoach-') && k !== VERSION).map((k) => caches.delete(k)))).then(() => self.clients.claim()));
});
self.addEventListener('fetch', (e) => {
  const req = e.request;
  if (req.method !== 'GET' || new URL(req.url).origin !== location.origin) return;
  e.respondWith(caches.match(req, { ignoreSearch: true }).then((hit) => hit || fetch(req).then((res) => {
    if (res.ok) { const copy = res.clone(); caches.open(VERSION).then((c) => c.put(req, copy)); }
    return res;
  }).catch(() => (req.mode === 'navigate' ? caches.match('./') : Response.error()))));
});
`;
fs.writeFileSync(path.join(root, 'sw.js'), sw);
console.log(`sw.js written: ${files.length} files, version ${version}, ${heavy.length} wasm`);
